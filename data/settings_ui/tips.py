def apply_tooltips(dlg) -> None:
    for name, text in TIPS.items():
        w = getattr(dlg, name, None)
        if w is None:
            continue
        try:
            w.setToolTip(text)
            if hasattr(w, "setWhatsThis"):
                w.setWhatsThis(text)
        except Exception:
            pass
    tabs = getattr(dlg, "tab_widget", None)
    if tabs is not None:
        for i, text in TAB_TIPS.items():
            if i < tabs.count():
                tabs.setTabToolTip(i, text)
    QtWidgets.QToolTip.setFont(dlg.font())
